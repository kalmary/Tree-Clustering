import struct

import numpy as np
from numpy.typing import NDArray
from scipy.spatial import Delaunay


def write_raycloud_ply(
    points: NDArray,
    path: str,
    rays: NDArray | None = None,
):
    n = len(points)
    pts = points.astype(np.float32)
    if rays is not None:
        rays = np.asarray(rays, dtype=np.float32)
        if rays.shape != (n, 3):
            raise ValueError(f"rays must have shape {(n, 3)}, not {rays.shape}")
    else:
        rays = np.tile(np.array([0, 0, 10], dtype=np.float32), (n, 1))
    times = np.zeros(n, dtype=np.float64)
    colors = np.full((n, 4), 128, dtype=np.uint8)

    with open(path, "wb") as f:
        f.write(
            (
                "ply\nformat binary_little_endian 1.0\n"
                "comment generated by TreeSegmRay\n"
                f"element vertex {n:010d}\n"
                "property float x\nproperty float y\nproperty float z\n"
                "property double time\n"
                "property float nx\nproperty float ny\nproperty float nz\n"
                "property uchar red\nproperty uchar green\n"
                "property uchar blue\nproperty uchar alpha\nend_header\n"
            ).encode("ascii")
        )
        for i in range(n):
            f.write(pts[i].tobytes())
            f.write(times[i].tobytes())
            f.write(rays[i].tobytes())
            f.write(colors[i].tobytes())


def write_ground_mesh_ply(ground_xyz: np.ndarray, path: str):
    if ground_xyz.shape[0] < 3:
        raise ValueError("Cannot build ground mesh from fewer than 3 points")

    tri = Delaunay(ground_xyz[:, :2])
    verts = ground_xyz.astype(np.float32)
    faces = tri.simplices.astype(np.int32)

    with open(path, "wb") as f:
        f.write(
            (
                "ply\nformat binary_little_endian 1.0\n"
                "comment generated by TreeSegmRay\n"
                f"element vertex {len(verts)}\n"
                "property float x\nproperty float y\nproperty float z\n"
                f"element face {len(faces)}\n"
                "property list uchar int vertex_indices\n"
                "end_header\n"
            ).encode("ascii")
        )
        f.write(verts.tobytes())
        f.writelines(
            struct.pack("<B3i", 3, face[0], face[1], face[2]) for face in faces
        )


def read_labels_from_segmented_ply(path: str) -> np.ndarray:
    with open(path, "rb") as f:
        header_lines = []
        while True:
            line = f.readline().decode("ascii").strip()
            header_lines.append(line)
            if line == "end_header":
                break

        n_points, props = 0, []
        for line in header_lines:
            if line.startswith("element vertex"):
                n_points = int(line.split()[-1])
            elif line.startswith("property"):
                parts = line.split()
                props.append((parts[1], parts[2]))

        type_map = {
            "float": "f",
            "float32": "f",
            "double": "d",
            "float64": "d",
            "int": "i",
            "int32": "i",
            "uint": "I",
            "uint32": "I",
            "short": "h",
            "ushort": "H",
            "uchar": "B",
            "uint8": "B",
            "char": "b",
            "int8": "b",
        }
        names = [n for _, n in props]
        fmt = "<" + "".join(type_map[t] for t, _ in props)
        stride = struct.calcsize(fmt)
        ri, gi, bi = names.index("red"), names.index("green"), names.index("blue")
        raw = f.read(n_points * stride)

    records = struct.iter_unpack(fmt, raw)
    colors = np.array([(r[ri], r[gi], r[bi]) for r in records], dtype=np.int32)
    packed = colors[:, 0] << 16 | colors[:, 1] << 8 | colors[:, 2]
    labels = np.full(len(packed), -1, dtype=np.int64)
    assigned = packed != 0
    _, labels[assigned] = np.unique(packed[assigned], return_inverse=True)
    return labels.astype(np.int64)
